// 把圖樣展開成音符陣列；stepBeats = 每格幾拍。
// '0'..'3' = 該軌一個音符；'_' = 把「上一個音符」延長一格（變成拉長音符 hold）；'-' = 休止。
// slowRows = [起始列, 結束列(不含)]：這段列的時間窗會記在 chart.slow，給「密集慢板」視覺放慢用。
function build(pattern, stepBeats, bpm, slowRows) {
  const spb = 60 / bpm
  const notes = []
  let beat = LEAD_BEATS
  let last = null
  let slow = null
  pattern.forEach((row, ri) => {
    if (slowRows && ri === slowRows[0]) slow = { from: beat * spb }
    for (const ch of row) {
      if (ch >= '0' && ch <= '3') {
        last = { time: beat * spb, lane: +ch, hold: 0, hit: false, judged: false, result: null, anim: 0, held: false, holdDone: false, broke: false }
        notes.push(last)
      } else if (ch === '_' && last) {
        last.hold += stepBeats * spb   // 延長上一個音符 → 拉長音符
      }
      beat += stepBeats
    }
    if (slowRows && ri === slowRows[1] - 1) slow.to = beat * spb
  })
  // 末尾留 4 拍尾音讓玩家踏穩、上船
  const endBeats = beat + 4
  const out = { notes, endBeats, endTime: endBeats * spb, bpm }
  if (slow) out.slow = slow
  return out
}

export function makeChart(mode, bpm) {
  if (mode === 'hell') return build(HELL, 0.5, bpm, [10, 16])  // rows 10–15 = 密集慢板段
  return mode === 'run' ? build(RUN, 0.5, bpm) : build(WALK, 1, bpm)
}
